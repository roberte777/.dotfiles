#!/usr/bin/env python3
"""
Kakashi site generator: content/*.md -> static HTML in site/.

Daily operation (the systemd user service runs `build.py --serve`):
  edit/add content/*.md, and the site rebuilds itself on the next request.
Manual:
  ./build.py            one-shot build into site/
  ./build.py --serve    build + serve; rebuilds when sources change

Frontmatter (optional --- block at top of each .md):
  title:  page <h1> and tab title (default: filename)
  desc:   one-line summary shown on the index
  date:   YYYY-MM-DD for ordering (default: file mtime)
  hidden: true  -> built, but not listed on the index
  draft:  true  -> not built at all

content/index.md body becomes the intro block on the homepage.
Link between pages with root-relative /slug.md and the builder rewrites
to real page URLs.
"""

import argparse
import datetime as dt
import os
import re
import shutil
import sys
from pathlib import Path

from markdown import Markdown
from pygments.formatters import HtmlFormatter

ROOT = Path(__file__).resolve().parent
CONTENT = ROOT / "content"
TEMPLATES = ROOT / "templates"
STATIC = ROOT / "static"
OUT = ROOT / "site"

SITE_NAME = "kakashi"
SITE_TAGLINE = "notes, ops, and pre-flight checklists from the box that runs this house"

FRONTMATTER_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)
LINK_RE = re.compile(r'href="/([\w\-/.]+)\.md"')
ANSWER_RE = re.compile(r"^:::answer\s*\n(.*?)\n:::\s*$", re.MULTILINE | re.DOTALL)


def extract_answers(text):
    """Replace :::answer ... ::: blocks with placeholders; return inner markdown list."""
    blocks = []

    def repl(m):
        blocks.append(m.group(1))
        return f"\n\nKAKASHI-ANSWER-{len(blocks) - 1}\n\n"

    return ANSWER_RE.sub(repl, text), blocks


def restore_answers(html, blocks, md_instance):
    """Render each captured block to markdown and swap it back in as <details>."""
    def repl(m):
        inner = md_instance.convert(blocks[int(m.group(1))])
        return (f'<details class="answer"><summary>Answer — try it yourself '
                f'first</summary><div class="answer-body">{inner}</div></details>')
    return re.sub(r"<(?:p|code)>KAKASHI-ANSWER-(\d+)</(?:p|code)>", repl, html)


def parse_frontmatter(text):
    meta = {}
    m = FRONTMATTER_RE.match(text)
    if m:
        for line in m.group(1).splitlines():
            stripped = line.strip()
            if ":" in line and not stripped.startswith("#"):
                key, _, val = line.partition(":")
                meta[key.strip().lower()] = val.strip().strip("\"'")
        text = text[m.end():]
    return meta, text


def slugify(value, separator):
    return re.sub(r"[^\w]+", separator, value.strip().lower()).strip(separator) or "section"


def make_md():
    return Markdown(
        extensions=["fenced_code", "tables", "toc", "codehilite", "attr_list", "sane_lists"],
        extension_configs={
            "toc": {"toc_depth": "2-3", "slugify": slugify},
            "codehilite": {"css_class": "highlight", "guess_lang": False},
        },
    )


def page_url(slug):
    return f"/{slug}.html" if "/" in slug else f"/{slug}/"


def load_pages():
    pages = []
    for path in sorted(CONTENT.rglob("*.md")):
        slug = path.relative_to(CONTENT).with_suffix("").as_posix()
        if slug == "index":
            continue
        meta, body_md = parse_frontmatter(path.read_text(encoding="utf-8"))
        if meta.get("draft", "").lower() == "true":
            continue
        body_md, answer_blocks = extract_answers(body_md)
        md = make_md()
        body = restore_answers(md.convert(body_md), answer_blocks, md)
        if not meta.get("date"):
            meta["date"] = dt.date.fromtimestamp(path.stat().st_mtime).isoformat()
        pages.append({
            "slug": slug,
            "title": meta.get("title") or slug.replace("-", " ").title(),
            "desc": meta.get("desc", ""),
            "date": meta["date"],
            "mtime": path.stat().st_mtime,
            "hidden": meta.get("hidden", "").lower() == "true",
            "body": body,
            "toc": getattr(md, "toc", ""),
        })
    # newest first; same-day pages ordered by last edit (mtime) descending
    pages.sort(key=lambda p: (p["date"], p["mtime"]), reverse=True)
    return pages


def render_code_css():
    """Pygments CSS for both themes, scoped so [data-theme] can override the
    OS-level prefers-color-scheme."""
    light = HtmlFormatter(style="default").get_style_defs(".highlight")
    dark = HtmlFormatter(style="one-dark").get_style_defs(".highlight")

    def scope(css, selector):
        return re.sub(r"^(\.highlight[^\n]*?\{)", lambda m: selector + " " + m.group(1), css, flags=re.MULTILINE)

    return "\n".join([
        "/* generated by build.py from pygments -- do not edit */",
        dark,  # default = dark-friendly; light block below overrides where supported
        f"@media (prefers-color-scheme: light) {{ {light} }}",
        f"[data-theme='dark'] {{ {dark} }}",
        f"[data-theme='light'] {{ {light} }}",
    ])


def build():
    """Full clean build. Returns (pages, urls_written)."""
    template = (TEMPLATES / "page.html").read_text(encoding="utf-8")
    built = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    pages = load_pages()
    urls = {p["slug"]: page_url(p["slug"]) for p in pages}
    urls["index"] = "/"

    def rewrite_links(html):
        return LINK_RE.sub(lambda m: 'href="' + urls.get(m.group(1).rsplit(".md", 1)[0].strip("/"), m.group(0)) + '"', html)

    def emit(out_rel, title, desc, canonical, body):
        html = (template
                .replace("@@TITLE@@", title)
                .replace("@@DESC@@", desc)
                .replace("@@CANONICAL@@", canonical)
                .replace("@@SITE_NAME@@", SITE_NAME)
                .replace("@@BUILT@@", built)
                .replace("@@BODY@@", body))
        dest = OUT / out_rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(html, encoding="utf-8")

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    written = []

    # homepage = index.md intro + generated entry list
    intro = ""
    index_md = CONTENT / "index.md"
    if index_md.exists():
        _, intro_md = parse_frontmatter(index_md.read_text(encoding="utf-8"))
        intro = make_md().convert(intro_md)
    entries = []
    for p in pages:
        if p["hidden"]:
            continue
        date = dt.date.fromisoformat(p["date"]).strftime("%d %b %Y")
        entries.append(
            '<a class="entry" href="{}">'
            '<div class="entry-head"><span class="entry-title">{}</span>'
            '<time class="entry-date">{}</time></div>'
            '<p class="entry-desc">{}</p></a>'.format(
                urls[p["slug"]], p["title"], date, p["desc"])
        )
    home = (
        '<div class="home">{intro}<section class="entries">'
        '<h2 class="entries-title">Entries</h2>{items}</section></div>'
    ).format(intro=intro, items="".join(entries) or '<p class="muted">Nothing written yet.</p>')
    emit("index.html", f"{SITE_NAME}", SITE_TAGLINE, "/", rewrite_links(home))
    written.append("/")

    # content pages
    for p in pages:
        url = urls[p["slug"]]
        out_rel = (p["slug"] + ".html") if url.endswith(".html") else (p["slug"].rstrip("/") + "/index.html")
        date = dt.date.fromisoformat(p["date"]).strftime("%d %b %Y")
        layout = (
            '<div class="page-layout">{toc}<article class="prose">'
            '<p class="page-meta"><time>{date}</time> · <a href="/">index</a></p>'
            "<h1 id=\"{slug}\">{title}</h1>{body}</article></div>"
        ).format(
            toc='<aside class="toc" aria-label="Table of contents"><p class="toc-title">On this page</p>' + p["toc"] + "</aside>" if '<nav' in p["toc"] or '<ul' in p["toc"] else "",
            date=date, slug=slugify(p["title"], "-"), title=p["title"], body=p["body"],
        )
        emit(out_rel, f"{p['title']} · {SITE_NAME}", p["desc"], url, rewrite_links(layout))
        written.append(url)

    # assets + 404 + robots
    if STATIC.exists():
        shutil.copytree(STATIC, OUT / "static")
    (OUT / "static").mkdir(exist_ok=True)
    (OUT / "static" / "code.css").write_text(render_code_css(), encoding="utf-8")
    emit("404.html", f"404 · {SITE_NAME}", "", "/404",
         '<div class="home"><h1>404</h1><p>This page doesn\'t exist. <a href="/">Back to the index.</a></p></div>')
    (OUT / "robots.txt").write_text("User-agent: *\nDisallow:\n\n", encoding="utf-8")
    return pages, written


def serve(host, port):
    """Serve site/, rebuilding on a timer when any source file changes.
    Rebuild-on-tick (0.5s) is simpler and safer than rebuilding inside the
    request path: a crash mid-build can never serve a half-written page."""
    import http.server
    import socketserver
    import threading

    state = {"sig": None}

    def signature():
        parts = []
        for d in (CONTENT, TEMPLATES, STATIC):
            if d.exists():
                for f in sorted(d.rglob("*")):
                    if f.is_file():
                        st = f.stat()
                        parts.append(f"{f}:{st.st_mtime_ns}")
        return "\n".join(parts)

    def maybe_rebuild(force=False):
        sig = signature()
        if force or sig != state["sig"]:
            state["sig"] = sig
            try:
                _, written = build()
                print(f"[kakashi] built {len(written)} pages", flush=True)
            except Exception as e:  # keep serving last good build
                print(f"[kakashi] BUILD FAILED (serving previous): {e}", file=sys.stderr, flush=True)

    def watch():
        import time
        while True:
            time.sleep(0.5)
            maybe_rebuild()

    class Server(socketserver.ThreadingTCPServer):
        allow_reuse_address = True
        daemon_threads = True

    handler = lambda *a, **kw: http.server.SimpleHTTPRequestHandler(*a, directory=str(OUT), **kw)
    maybe_rebuild(force=True)
    threading.Thread(target=watch, daemon=True).start()
    with Server((host, port), handler) as httpd:
        print(f"[kakashi] serving http://{host}:{port} -> {OUT}", flush=True)
        httpd.serve_forever()


def main():
    ap = argparse.ArgumentParser(description="build/serve the kakashi site")
    ap.add_argument("--serve", action="store_true")
    ap.add_argument("--host", default=os.environ.get("KAKASHI_HOST", "127.0.0.1"))
    ap.add_argument("--port", type=int, default=int(os.environ.get("KAKASHI_PORT", "8404")))
    args = ap.parse_args()
    if args.serve:
        serve(args.host, args.port)
    else:
        _, written = build()
        print(f"built {len(written)} pages -> {OUT}")
        for u in written:
            print("  ", u)


if __name__ == "__main__":
    main()
